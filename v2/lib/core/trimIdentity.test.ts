function newCuts(st: GameState, before: Set<GameState["log"][number]>): number[] {
  return st.log.flatMap((e) => (
    e.cut && typeof e.playerId === "number" && !before.has(e) ? [e.playerId] : []
  ));
}

/** Walk seed 42 to the Roster Cutdown click that opens `target`, and stop on that door. */
function atCutdownDoor(target: number): GameState {
  const st = newGame({ seed: 42 });
  advance(st);
  while (true) {
    let g = 0;
    while (st.phase === "regular" && g++ < 40) advance(st);
    let p = 0;
    while (st.phase !== "offseason-recap" && p++ < 12) advance(st);
    let o = 0;
    while (isOffseason(st.phase) && o++ < 20) {
      const weeks = st.phase === "offseason-final" ? preseasonWeeksLeft(st) : -1;
      if (st.phase === "offseason-final" && weeks === 0 && st.season + 1 === target) return st;
      advanceOffseason(st);
    }
    if (st.phase !== "preseason") throw new Error(`stuck in ${st.season} ${st.phase}`);
    if (st.season >= target) throw new Error(`passed the ${target} cutdown`);
    advance(st);
  }
}

